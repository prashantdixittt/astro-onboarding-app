export const getMCQsByExperience = (experienceType, yearsOfExperience) => {
  const questions = mcqQuestions[experienceType] || mcqQuestions["Tarot"];
  
  let difficulty;
  if (yearsOfExperience <= 2) {
    difficulty = "beginner";
  } else if (yearsOfExperience <= 5) {
    difficulty = "intermediate";
  } else {
    difficulty = "expert";
  }
  
  // Get questions for the difficulty level, fallback to beginner if not available
  const availableQuestions = questions[difficulty] || questions["beginner"] || questions["intermediate"];
  
  // Return up to 10 questions, or all available if less than 10
  return availableQuestions.slice(0, 10);
};